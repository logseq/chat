fun logseqChatExtensionRegistry(
    resolveAssetPath: (String) -> String = { it },
): LuiExtensionRegistry = LuiExtensionRegistry().apply {
    register("outliner-editor", EDITOR_FINGERPRINT) { context ->
        OutlinerEditor(context)
    }
    register("outliner-block-content", RICH_FINGERPRINT) { context ->
        OutlinerBlockContent(context, resolveAssetPath)
    }
    register("native-navigation-stack", NAVIGATION_FINGERPRINT) { context ->
        NavigationBoundary(context)
    }
    register("native-search-presentation", SEARCH_FINGERPRINT) { context ->
        SearchPresentation(context)
    }
}

// Android hardware-back routing, mirroring the former PopScope semantics:
// composer dismissal takes precedence, then nav-stack back, then the
// system.
@Composable
private fun NavigationBoundary(context: LuiExtensionContext) {
    val depth = context.int("depth") ?: 0
    val dismissesComposer = context.flag("composer-dismissal-enabled")
    BackHandler(enabled = depth > 0 || dismissesComposer) {
        if (dismissesComposer) {
            context.emit("dismiss-composer")
        } else if (depth > 0) {
            context.emit("back", "count" to 1)
        }
    }
    context.Children()
}

// Modal search sheet — the core drives `query`; results are standard
// children rendered below the field.
@Composable
private fun SearchPresentation(context: LuiExtensionContext) {
    val presented = context.flag("presented")
    if (!presented) return
    val title = context.string("title") ?: ""
    val query = context.string("query") ?: ""

    BackHandler {
        context.emit("dismiss")
    }
    Surface(
        modifier = Modifier
            .fillMaxSize()
            .testTag("native-search-presentation"),
        color = MaterialTheme.colorScheme.surface,
    ) {
        Column {
            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .padding(horizontal = 4.dp, vertical = 4.dp),
                verticalAlignment = Alignment.CenterVertically,
            ) {
                IconButton(onClick = { context.emit("back", "count" to 1) }) {
                    Icon(
                        Icons.AutoMirrored.Filled.ArrowBack,
                        contentDescription = "Back",
                    )
                }
                var fieldValue by remember(query) { mutableStateOf(query) }
                TextField(
                    value = fieldValue,
                    onValueChange = {
                        fieldValue = it
                        context.emit("query-changed", "query" to it)
                    },
                    modifier = Modifier
                        .weight(1f)
                        .testTag("field.search"),
                    placeholder = { Text(title.ifEmpty { "Search" }) },
                    singleLine = true,
                )
                if (fieldValue.isNotEmpty()) {
                    IconButton(
                        onClick = {
                            fieldValue = ""
                            context.emit("query-changed", "query" to "")
                        },
                    ) {
                        Icon(Icons.Filled.Close, contentDescription = "Clear")
                    }
                }
            }
            Box(modifier = Modifier.fillMaxSize()) {
                context.Children()
            }
        }
    }
}
